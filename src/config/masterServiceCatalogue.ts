function packageRecord(
  id: string,
  roomId: string,
  section: MasterServiceCatalogue['sections'][number]['id'],
  customerName: { en: string; es: string },
  internalName: string,
  sortOrder: number,
  quote = false,
  copy: {
    shortDescription?: { en: string; es: string }
    customerBenefit?: { en: string; es: string }
  } = {},
): MasterServiceCatalogue['packages'][number] {
  const defaultPricing = defaultPackagePricing[id]

  return {
    id,
    slug: id,
    roomId,
    section,
    customerName,
    internalName,
    shortDescription: copy.shortDescription ?? { en: 'A coordinated package of customer outcomes.', es: 'Un paquete coordinado de resultados para el cliente.' },
    customerBenefit: copy.customerBenefit ?? { en: 'One clear plan instead of disconnected products.', es: 'Un plan claro en lugar de productos sueltos.' },
    active: true,
    sortOrder,
    pricingType: quote ? 'quote' : 'from',
    fromPrice: quote ? undefined : defaultPricing?.fromPrice,
    recurringMonthlyPrice: defaultPricing?.recurringMonthlyPrice,
    vatRate: 0.21,
    requiresAssessment: true,
    requiresSiteVisit: quote,
    requiresQuote: quote,
    wizardVisible: true,
    websiteVisible: true,
    proposalVisible: true,
    inspectorVisible: true,
    adminVisible: true,
    version: '1.0.0',
    createdAt: now,
    updatedAt: now,
  }
}

